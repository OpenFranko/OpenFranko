Map::Map() {
  dirt =
      textureManager::TextureManager::LoadTexture("assets/0035/0035_003.bmp");
  grass =
      textureManager::TextureManager::LoadTexture("assets/0035/0035_004.bmp");
  water =
      textureManager::TextureManager::LoadTexture("assets/0035/0035_005.bmp");

  loadMap(lvl1);

  src.x = 0;
  src.y = 0;
  dest.x = 0;
  dest.y = 0;
  src.w = 15;
  src.h = 15;
  dest.w = 32;
  dest.h = 32;
}

void Map::loadMap(int arr[20][25]) {
  for (int row = 0; row < 20; row++) {
    for (int column = 0; column < 25; column++) {
      map[row][column] = arr[row][column];
    }
  }
}

void Map::drawMap() {
  int type = 0;
  for (int row = 0; row < 20; row++) {
    for (int column = 0; column < 25; column++) {
      type = map[row][column];

      dest.x = column * 32;
      dest.y = row * 32;

      switch (type) {
      case 0:
        textureManager::TextureManager::draw(dirt, src, dest);
        break;
      case 1:
        textureManager::TextureManager::draw(grass, src, dest);
        break;
      case 2:
        textureManager::TextureManager::draw(water, src, dest);
        break;
      default:
        break;
      }
    }
  }
}

