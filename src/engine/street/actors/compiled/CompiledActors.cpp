template <std::size_t LENGTH>
constexpr amal::Program program(const std::array<uint16_t, LENGTH> &code) {
  return amal::Program{code.data(), INSTRUCTIONS.data(), TERMS.data(),
                       FRAMES.data(), static_cast<int16_t>(LENGTH)};
}

template <typename Value, std::size_t COUNT>
std::size_t position(const std::array<Value, COUNT> &values, Value value,
                     const char *what) {
  for (std::size_t i = 0; i < COUNT; ++i) {
    if (values[i] == value) {
      return i;
    }
  }
  throw std::out_of_range(std::string("AMAL: no compiled ") + what);
}

